"""Subset currently used solid icons; keep Font Awesome's full face as fallback.

Run with fonttools[woff]==4.68.0. Generated files are committed, so normal builds
do not require Python. Preserve the original outlines, metrics and license.
"""
import hashlib
import json
from pathlib import Path
import re

from fontTools import subset
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "node_modules/@fortawesome/fontawesome-free"
source = PACKAGE / "webfonts/fa-solid-900.woff2"
names = set()
for folder in ["app", "components", "lib"]:
    for path in (ROOT / folder).rglob("*"):
        if path.is_file() and path.suffix in {".ts", ".tsx", ".css"}:
            names.update(re.findall(r"\bfa-([a-z0-9-]+)", path.read_text(encoding="utf-8")))
metadata = json.loads((PACKAGE / "metadata/icon-families.json").read_text(encoding="utf-8"))
codes = set()
covered_names = set()
for name, item in metadata.items():
    aliases = item.get("aliases", {})
    if not names.intersection([name, *aliases.get("names", [])]):
        continue
    if {"family": "classic", "style": "solid"} not in item["familyStylesByLicense"]["free"]:
        continue
    codes.add(int(item["unicode"], 16))
    covered_names.update(names.intersection([name, *aliases.get("names", [])]))

original = TTFont(source, recalcTimestamp=False)
codes.intersection_update(original.getBestCmap())
font = TTFont(source, recalcTimestamp=False)
options = subset.Options()
options.layout_features = ["*"]
options.name_IDs = ["*"]
options.name_languages = ["*"]
options.name_legacy = True
options.glyph_names = True
options.recalc_timestamp = False
subsetter = subset.Subsetter(options=options)
subsetter.populate(unicodes=codes)
subsetter.subset(font)
# The OFL reserves the upstream primary font name for unmodified fonts.
# Keep copyright/license records, but give this subset its own family and ID.
for entry in font["name"].names:
    replacement = {1: "DDB UI Icons", 3: "DDBUIIcons-Used-1", 4: "DDB UI Icons Used", 6: "DDBUIIcons-Used", 16: "DDB UI Icons"}.get(entry.nameID)
    if replacement:
        entry.string = replacement.encode(entry.getEncoding())
font.flavor = "woff2"
output = ROOT / "public/fonts/app-subsets/fa-solid-used.woff2"
font.save(output)
verified = TTFont(output)
assert set(verified.getBestCmap()) == codes
for code in codes:
    glyphs = []
    for face in [original, verified]:
        name = face.getBestCmap()[code]
        pen = DecomposingRecordingPen(face.getGlyphSet())
        face.getGlyphSet()[name].draw(pen)
        glyphs.append((pen.value, face["hmtx"].metrics[name]))
    assert glyphs[0] == glyphs[1], hex(code)
for table, fields in [("head", ["unitsPerEm"]), ("hhea", ["ascent", "descent", "lineGap"])]:
    for field in fields:
        assert getattr(original[table], field) == getattr(verified[table], field)

license_text = (PACKAGE / "LICENSE.txt").read_text(encoding="utf-8")
(output.parent / "fontawesome-LICENSE.txt").write_text(license_text, encoding="utf-8")
unicode_range = ",".join(f"U+{code:X}" for code in sorted(codes))
selectors = ",".join(".fa-" + name for name in sorted(covered_names))
(ROOT / "app/app-icons.generated.css").write_text(
    '/*! Font Awesome Free 7.2.0, Copyright 2026 Fonticons, Inc.\n'
    ' * Fonts: SIL OFL 1.1. Full license: /fonts/app-subsets/fontawesome-LICENSE.txt\n'
    ' * Generated by scripts/subset-app-icons.py. Original full face stays as fallback. */\n'
    '@font-face { font-family: "DDB UI Icons"; font-style: normal; font-weight: 900; font-display: block; '
    'src: url("/fonts/app-subsets/fa-solid-used.woff2") format("woff2"); '
    f'unicode-range: {unicode_range}; }}\n'
    # Giving every icon the full face as a secondary family downloads that
    # face for fallback metrics even when all visible glyphs use the subset.
    # Select only proven subset classes; unlisted/dynamic icons keep the
    # original Font Awesome family from the upstream stylesheet.
    f':is(.fa-solid,.fas):is({selectors}) {{ --fa-family: "DDB UI Icons"; }}\n', encoding="utf-8")
receipt = {
    "source": source.relative_to(ROOT).as_posix(), "file": output.relative_to(ROOT).as_posix(),
    "sourceSha256": hashlib.sha256(source.read_bytes()).hexdigest(),
    "sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
    "sourceBytes": source.stat().st_size, "bytes": output.stat().st_size,
    "characters": len(codes), "allOutlinesAndMetricsMatch": True,
}
(ROOT / "scripts/app-icons.generated.json").write_text(json.dumps(receipt, indent=2)+"\n", encoding="utf-8")
print(json.dumps(receipt))
