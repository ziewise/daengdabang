#!/usr/bin/env node
/**
 * gen-hero-manifest — 히어로 영상 폴더를 스캔해 "영상 + 등장 견종" 매니페스트 자동 생성
 * ---------------------------------------------------------------------
 * 배경:
 *   히어로 배경은 날씨 × 시간대 × 기기(PC/모바일)로 고른다. 영상 파일명만 규칙대로 두면
 *   이 스크립트가 폴더를 스캔해 매핑을 자동 생성 → 영상을 추가/교체할 때 코드 수정 불필요.
 *
 * 2026-10-28 가을 교체:
 *   · 여름(steady-walk-v3, 24개 · 견종 3종) → 가을(fall-v1, 16개 · 견종 이름 없음)
 *   · 가을 영상은 날씨가 맑음/비 2종뿐 → "흐림"은 같은 시간대의 맑음 영상을 쓴다(사용자 요청)
 *   · 여름 영상은 Git 에 원본 보존 + 배포에서만 제외(scripts/prepare-pages-artifact.mjs)
 *
 * 파일명 규칙: {season}_{time}_{weather}[_{breed}]_{device}.mp4
 *   · 예) fall_night_rainy_m.mp4 / summer_night_cloudy_welshcorgi_m.mp4
 *   · weather: sunny / rain(=rainy) / cloudy(없으면 sunny 로 대신)
 *   · breed(선택) = public/images/breeds 의 파일명과 동일(welshcorgi / englishbulldog / poodle …)
 *     생략하면 breed=null → 화면에서 기본 견종 배지(lib/hero-summer-video.ts FALLBACK_BREED)
 *
 * 출력: lib/hero-video-manifest.ts  (자동 생성물, 직접 수정 금지)
 *   형태: { "{time}_{weather}": { breed, pc, m } }
 *   · time/weather 가 같으면 PC·모바일이 같은 장면이므로 한 항목으로 묶고 견종 공유
 *
 * 실행: node scripts/gen-hero-manifest.mjs  (npm run dev/build 시 자동 — package.json predev/prebuild)
 */
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
// 지금 히어로에 쓰는 영상 폴더(가을, 워터마크 지움 · 소리 뺌 · 압축 — 2026-10-28)
const HERO_VIDEO_PATH = "/images/hero/fall-v1";
const HERO_DIR = join(root, "public", HERO_VIDEO_PATH.slice(1));
const OUT = join(root, "lib/hero-video-manifest.ts");

// 파일명 날씨 표기 → 화면 날씨 3종(sunny/rain/cloudy)
const WEATHER_ALIAS = { sunny: "sunny", rain: "rain", rainy: "rain", cloudy: "cloudy" };

const files = readdirSync(HERO_DIR).filter((f) => f.endsWith(".mp4")).sort();

/** @type {Record<string, { breed: string | null, pc: string | null, m: string | null }>} */
const manifest = {};

for (const file of files) {
    const parts = file.replace(/\.mp4$/, "").split("_");
    if (parts.length < 4) continue; // 규칙 밖 파일은 스킵

    const device = parts[parts.length - 1]; // pc | m (항상 마지막)
    if (device !== "pc" && device !== "m") continue;
    const time = parts[1]; // season(0) _ time(1) _ weather(2) ...
    const weather = WEATHER_ALIAS[parts[2]];
    if (!weather) continue; // 모르는 날씨 표기는 스킵
    // 시간/날씨 뒤, 기기 앞에 토큰이 있으면 견종(여러 토큰이면 '_'로 합침)
    const breed = parts.length >= 5 ? parts.slice(3, -1).join("_") : null;

    const key = `${time}_${weather}`;
    manifest[key] ??= { breed: null, pc: null, m: null };
    manifest[key][device] = `${HERO_VIDEO_PATH}/${file}`;
    if (breed) manifest[key].breed = breed; // 견종은 PC/모바일 중 하나라도 있으면 채움
}

for (const time of ["morning", "afternoon", "evening", "night"]) {
    // 맑음 · 비는 시간대마다 PC/모바일 모두 있어야 함
    for (const weather of ["sunny", "rain"]) {
        const entry = manifest[`${time}_${weather}`];
        if (!entry?.pc || !entry?.m) {
            throw new Error(`Missing hero scene: ${time}_${weather}`);
        }
    }
    // 흐림 영상이 없으면 같은 시간대 맑음 영상을 그대로 씀(2026-10-28 사용자 요청)
    const cloudy = manifest[`${time}_cloudy`];
    if (!cloudy?.pc || !cloudy?.m) manifest[`${time}_cloudy`] = { ...manifest[`${time}_sunny`] };
}

// 키 순서 고정(시간 → 날씨) — 폴더 순서와 상관없이 같은 결과
const ordered = {};
for (const time of ["morning", "afternoon", "evening", "night"]) {
    for (const weather of ["sunny", "rain", "cloudy"]) ordered[`${time}_${weather}`] = manifest[`${time}_${weather}`];
}

const banner =
    "// AUTO-GENERATED by scripts/gen-hero-manifest.mjs — 직접 수정하지 말 것.\n" +
    `// public${HERO_VIDEO_PATH} 스캔 결과: "{시간}_{날씨}" → { breed, pc, m }. 흐림 영상이 없으면 맑음 영상.\n` +
    "// 영상 추가/교체 후 `node scripts/gen-hero-manifest.mjs`(또는 npm run dev/build)로 갱신됨.\n";

writeFileSync(
    OUT,
    `${banner}export const HERO_VIDEO_MANIFEST = ${JSON.stringify(ordered, null, 4)} as const;\n`,
);

console.log(`✓ hero-video-manifest.ts 생성: ${Object.keys(ordered).length} 장면 / ${files.length} 파일`);
