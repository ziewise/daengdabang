import { readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";

// Other sticker screens still consume these canonical style strings. The
// startup route uses their identical CSS without shipping/parsing them again
// as JavaScript and inserting a second copy during hydration.
const directory = new URL("../components/pwa/home-concepts/", import.meta.url);
const sources = [["kit.tsx", "KIT_CSS"], ["shared.tsx", "HC_CSS"], ["sticker-kit.tsx", "STICKER_CSS"]];
const styles = sources.map(([file, name]) => {
    const code = readFileSync(new URL(file, directory), "utf8");
    const source = ts.createSourceFile(file, code, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
    let css;
    function visit(node) {
        if (ts.isVariableDeclaration(node) && node.name.getText(source) === name) {
            if (!node.initializer || !ts.isNoSubstitutionTemplateLiteral(node.initializer)) {
                throw new Error(`${name} must remain static CSS`);
            }
            css = node.initializer.text;
        }
        ts.forEachChild(node, visit);
    }
    visit(source);
    if (!css) throw new Error(`Missing ${name}`);
    return css;
}).join("\n");
const output = new URL("home-shared.generated.css", directory);
const contents = "/* Generated by scripts/gen-home-styles.mjs; preserve shared style order. */\n" + styles;
if (process.argv.includes("--check")) {
    if (readFileSync(output, "utf8") !== contents) throw new Error("Run node scripts/gen-home-styles.mjs after editing shared home styles");
} else {
    writeFileSync(output, contents);
}
