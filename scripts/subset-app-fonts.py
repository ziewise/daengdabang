"""Rebuild app font slices with fonttools[woff]==4.68.0.

Generated files are committed; ordinary web/native builds need no Python font
dependency. Keep every original glyph and verify its shape and metrics.
"""
import hashlib
import json
from pathlib import Path
import re

from fontTools import subset
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "public/fonts"
OUTPUT = FONTS / "app-subsets"
SOURCES = [("Cafe24Ssurround", "Cafe24Ssurround", 400),
           ("NanumSquareRoundB", "NanumSquareRound", 700),
           ("NanumSquareRoundR", "NanumSquareRound", 400)]
UI_SOURCES = [
    "components/app-shell/AppShell.tsx", "components/app-shell/appTabs.ts",
    "components/pwa/home-concepts/HomeSticker.tsx", "components/pwa/home-concepts/kit.tsx",
    "components/pwa/home-concepts/sticker-kit.tsx", "components/pwa/home-concepts/shared.tsx",
    "components/pwa/home-concepts/sticker-parts.tsx", "components/pwa/home-concepts/pages/StickerShop.tsx",
    "components/pwa/home-concepts/shop/ShopHero.tsx", "components/pwa/home-concepts/pages/StickerShow.tsx",
    "lib/menu-data.ts", "lib/hero-assets.ts",
    "components/pwa/home-concepts/shop/ShopShelf.tsx", "components/pwa/home-concepts/shop/ShopHotPick.tsx",
    "components/pwa/home-concepts/shop/ShopProductCard.tsx", "lib/catalog/price-badge.ts", "lib/catalog/inventory.ts",
]


def source_codes(names):
    codes = set(range(0x20, 0x7f))
    for name in names:
        source_text = (ROOT / name).read_text(encoding="utf-8")
        source_text = re.sub(r"/\*.*?\*/", "", source_text, flags=re.S)
        source_text = re.sub(r"//[^\n]*", "", source_text)
        codes.update(ord(character) for character in source_text)
    return codes


def common(code):
    # Conjoining Jamo belong together in the extra slice: placing them in the
    # common slice pulls every composed Hangul glyph back through GSUB closure.
    if code < 0x250 or 0x2000 <= code <= 0x22ff or 0x3000 <= code <= 0x318f:
        return True
    if 0xac00 <= code <= 0xd7a3:
        try:
            return len(chr(code).encode("euc_kr")) == 2
        except UnicodeEncodeError:
            return False
    return False


def ranges(codes):
    spans = []
    for code in sorted(codes):
        if spans and code == spans[-1][1] + 1:
            spans[-1][1] = code
        else:
            spans.append([code, code])
    return ",".join(f"U+{first:X}" if first == last else f"U+{first:X}-{last:X}" for first, last in spans)


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def outline(glyphs, glyph):
    pen = DecomposingRecordingPen(glyphs)
    glyphs[glyph].draw(pen)
    return pen.value


def main():
    OUTPUT.mkdir(exist_ok=True)
    ui_codes = source_codes(UI_SOURCES)
    # The small native catalog is already bundled. Cover its first shelf names
    # too, so scrolling to products does not trigger another font/layout pass.
    catalog = json.loads((ROOT / "lib/catalog/native-shop.generated.json").read_text(encoding="utf-8"))
    for product in catalog["products"]:
        for field in ["name", "nameEn", "brand"]:
            ui_codes.update(ord(character) for character in str(product.get(field, "")))
    css = ["/* Generated by scripts/subset-app-fonts.py. Original shapes and full character coverage retained. */"]
    receipt = []
    for name, family, weight in SOURCES:
        source = FONTS / (name + ".woff2")
        original = TTFont(source, recalcTimestamp=False)
        cmap = original.getBestCmap()
        original_glyphs = original.getGlyphSet()
        covered = set()
        slices = []
        common_codes = sorted(code for code in cmap if code not in ui_codes and common(code))
        # A single uncommon author/pet name used to activate a 126–172 KB
        # face. Bound those on-demand slices without changing any glyph.
        # Keep the home/shop/show UI together: splitting those three screens
        # causes a second font/layout pass during the first tab transition.
        groups = [("startup", set(cmap).intersection(ui_codes))]
        groups.extend((f"common-{index // 192:02}", set(common_codes[index:index + 192]))
                      for index in range(0, len(common_codes), 192))
        groups.append(("extra", {code for code in cmap if code not in ui_codes and not common(code)}))
        for label, codes in groups:
            font = TTFont(source, recalcTimestamp=False)
            options = subset.Options()
            options.layout_features = ["*"]
            options.name_IDs = ["*"]
            options.name_languages = ["*"]
            options.name_legacy = True
            options.glyph_names = True
            options.recalc_timestamp = False
            subsetter = subset.Subsetter(options=options)
            subsetter.populate(unicodes=codes)
            subsetter.subset(font)
            font.flavor = "woff2"
            target = OUTPUT / f"{name}-{label}.woff2"
            font.save(target)
            check = TTFont(target)
            check_cmap = check.getBestCmap()
            assert set(check_cmap) == codes and not covered.intersection(codes)
            assert check["head"].unitsPerEm == original["head"].unitsPerEm
            for field in ["ascent", "descent", "lineGap"]:
                assert getattr(check["hhea"], field) == getattr(original["hhea"], field)
            glyphs = check.getGlyphSet()
            for code in codes:
                assert check["hmtx"][check_cmap[code]] == original["hmtx"][cmap[code]]
                assert outline(glyphs, check_cmap[code]) == outline(original_glyphs, cmap[code]), hex(code)
            covered.update(codes)
            css.append(f'@font-face {{ font-family: "{family}"; font-weight: {weight}; font-display: swap; '
                       f'src: url("/fonts/app-subsets/{target.name}") format("woff2"); unicode-range: {ranges(codes)}; }}')
            slices.append({"file": str(target.relative_to(ROOT)).replace("\\", "/"),
                           "sha256": digest(target), "bytes": target.stat().st_size, "characters": len(codes)})
        assert covered == set(cmap)
        receipt.append({"source": str(source.relative_to(ROOT)).replace("\\", "/"),
                        "sourceSha256": digest(source), "sourceBytes": source.stat().st_size,
                        "characters": len(cmap), "allOutlinesAndMetricsMatch": True, "slices": slices})
    (ROOT / "app/app-fonts.generated.css").write_text("\n".join(css) + "\n", encoding="utf-8")
    (ROOT / "scripts/app-fonts.generated.json").write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(receipt))


if __name__ == "__main__":
    main()
